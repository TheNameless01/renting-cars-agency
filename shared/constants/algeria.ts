/**
 * Standard Algerian registration plate format:
 * Group 1: 5 or 6 digits (serial)
 * Group 2: 3 digits (1st digit = class 1..9, 2nd-3rd = year)
 * Group 3: 2 digits (wilaya code 01..69)
 * Accepts hyphen or space separators (e.g. "00123-124-16" or "02639 126 09").
 */
export const STANDARD_ALGERIAN_MATRICULE_REGEX = /^\d{5,6}[-\s]\d{3}[-\s](0[1-9]|[1-6]\d)$/;

/**
 * Minor unit scaling factor (1 DZD = 100 centimes; 1 EUR = 100 cents).
 * All financial values are stored in integer minor units in SQLite.
 */
export const MINOR_UNIT_FACTOR = 100;

export function toMinorUnits(majorAmount: number): number {
  return Math.round(majorAmount * MINOR_UNIT_FACTOR);
}

export function fromMinorUnits(minorAmount: number): number {
  return minorAmount / MINOR_UNIT_FACTOR;
}

